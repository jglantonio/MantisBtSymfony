<?php

namespace App\Tests\Controller;

use App\Entity\User;
use App\Enum\BugPriority;
use App\Enum\BugStatus;
use Symfony\Bundle\FrameworkBundle\Test\WebTestCase;

final class BugControllerTest extends WebTestCase
{
    private $em;
    private $user;
    private $client;
    private $connection;
    public function setUp(): void
    {
        $user = new User();
        $user->setUsername('johndoe');
        $user->setRealName("John Doe");
        $user->setEnabled(1);
        $user->setEmail("jonDoe@f.gob");
        $user->setProtected(false);
        $user->setAccessLevel(10);
        $user->setPassword("ffff");


        $this->client = static::createClient();
        $container = self::getContainer();
        $this->em = $container->get('doctrine.orm.entity_manager');
        $this->connection = $container->get('database_connection');
        $this->user = $user;
        parent::setUp(); // TODO: Change the autogenerated stub
    }
    public function tearDown(): void
    {


        if($this->user && $this->user->getId()){
            $this->em->remove($this->em->getReference(User::class, $this->user->getId()));
            $this->em->flush();
        }

        $this->connection->delete('mantis_bug_table', ['id' => 90010]);
        parent::tearDown(); // TODO: Change the autogenerated stub
    }

    public static function dataProviderUrls(){
        yield "Bug" => ['/bug','/'];
        yield "Bug > Create" => ['/bug/create','/'];
        yield "Bug > Edit" => ['/bug/edit/1','/'];
        yield "Bug > Show > id" => ['/bug/show/1','/'];
    }

    /**
     * @dataProvider dataProviderUrls
     * @return void
     */
    public function testAccessWithOutLogin($from,$to): void
    {
        $this->client->request('GET', $from);
        self::assertResponseRedirects($to);
    }

    public function testEdit(){


        if($this->user && $this->user->getId()){
            $this->em->remove($this->em->getReference(User::class, $this->user->getId()));
            $this->em->flush();
        }

        $this->connection->sele('mantis_bug_text_table', [
            'id'              => 1000,
            'description' => "Lorem Ipsum",
            'steps_to_reproduce' => "Dolor amet",
            'additional_information' => "Sin amet",
        ]);

        $this->connection->insert('mantis_bug_text_table', [
            'id'              => 1000,
            'description' => "Lorem Ipsum",
            'steps_to_reproduce' => "Dolor amet",
            'additional_information' => "Sin amet",
        ]);


        if($this->user && $this->user->getId()){
            $this->em->remove($this->em->getReference(User::class, $this->user->getId()));
            $this->em->flush();
        }

        $this->connection->insert('mantis_bug_table', [
            'id'              => 90010,
            'reporter_id'     => $this->user->getId(),   // FK a mantis_user_table
            'handler_id'      => $this->user->getId(),
            'duplicated_id'   => 0,
            'priority'        => BugPriority::Normal->value,
            'severity'        => 10,
            'reproducibility' => 10,
            'status'          => BugStatus::Confirmed->value,
            'resolution'      => 10,
            'eta'             => 10,
            'bug_text_id'     => 1000,
            'summary'         => 'Test',
            'last_updated'    => time(),
            'date_submitted'  => time(),
        ]);




        $this->em->persist($this->user);
        $this->em->flush();
        $this->client->loginUser($this->user);
        $this->client->request('GET', '/bug/edit/90010');
        self::assertResponseIsSuccessful($this->client->getResponse());
    }
}
